/**
 * Generates `precache-manifest.js` for the service worker.
 *
 * The project has no bundler, so there is no build tool to hand the service
 * worker a list of files to cache. This walks the source tree instead and emits
 * that list, plus a version stamped from the contents of every file — so the
 * version changes exactly when something cacheable changes, and never otherwise.
 * That is what makes the "new version available" prompt trustworthy rather than
 * firing on every deploy.
 *
 * Run it via `npm run precache`. Vercel runs it automatically on deploy
 * (see buildCommand in vercel.json), so a forgotten manual run can't ship a
 * stale cache.
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

// Directories whose contents the app shell needs to boot and play offline.
const DIRS = ['src', 'shared', 'styles', 'assets'];
const FILES = ['index.html', 'manifest.webmanifest'];

// Never cache: server code, tooling, docs, and the worker's own scaffolding.
const SKIP_DIRS = new Set(['node_modules', '.git', '.vercel', 'api', 'scripts']);
const SKIP_EXT = new Set(['.md', '.mjs', '.py', '.zip']);

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry) || entry.startsWith('.')) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (![...SKIP_EXT].some((ext) => entry.endsWith(ext))) out.push(full);
  }
  return out;
}

const found = [];
for (const file of FILES) found.push(join(ROOT, file));
for (const dir of DIRS) {
  try {
    walk(join(ROOT, dir), found);
  } catch {
    /* an optional directory is missing — fine */
  }
}

const hash = createHash('sha256');
const assets = found
  .map((full) => {
    hash.update(readFileSync(full));
    return `/${relative(ROOT, full).split(sep).join('/')}`;
  })
  .sort();

// The root path is what a launched installed app actually requests.
assets.unshift('/');

const version = hash.digest('hex').slice(0, 12);

const banner = '// GENERATED by scripts/gen-precache.mjs — do not edit by hand.\n';
writeFileSync(
  join(ROOT, 'precache-manifest.js'),
  `${banner}self.NVP_PRECACHE = ${JSON.stringify({ version, assets }, null, 2)};\n`,
);

console.log(`precache-manifest.js → ${assets.length} files, version ${version}`);
